#!/usr/bin/env python3
"""Figure 7c/7d: training-time and single-sample inference-latency bars.

Reads the validated table generated by scripts/run_efficiency_measurement.sh.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from figure_data import display_name  # noqa: E402

plt.rcParams.update({
    "font.family": "serif",
    "font.size": 9,
    "pdf.fonttype": 42,
})

GROUP_COLORS = {"proposed": "#BF1F3A", "timeseries": "#E8952F", "tabular": "#4F8FC0"}
GROUPS = {
    "UHI-E3LLM": "proposed",
    "ARMD": "timeseries",
    "FilterNet": "timeseries",
    "ST-MTM": "timeseries",
    "XGBoost": "tabular",
    "RandomForest": "tabular",
    "LightGBM": "tabular",
    "MLP": "tabular",
}
TRAINING_ORDER = [
    ("UHI-E3LLM", "SFT"), ("UHI-E3LLM", "PPO"),
    ("UHI-E3LLM", "Distillation"), ("UHI-E3LLM", "Total"),
    ("ARMD", "train"), ("FilterNet", "train"), ("ST-MTM", "train"),
    ("XGBoost", "train"), ("RandomForest", "train"),
    ("LightGBM", "train"), ("MLP", "train"),
]
INFERENCE_ORDER = [
    "UHI-E3LLM", "ARMD", "FilterNet", "ST-MTM",
    "XGBoost", "RandomForest", "LightGBM", "MLP",
]


def _save(figure, out_dir: Path, stem: str) -> None:
    for suffix in ("png", "pdf"):
        figure.savefig(out_dir / f"{stem}.{suffix}", dpi=600, bbox_inches="tight")
    plt.close(figure)
    print(f"[fig] {out_dir / stem}.png/.pdf")


def _bar(labels, values, colors, ylabel, out_dir, stem):
    figure, axis = plt.subplots(figsize=(6.4, 3.4))
    positions = np.arange(len(labels))
    axis.bar(positions, values, color=colors, width=0.65)
    axis.set_yscale("log")
    axis.set_xticks(positions)
    axis.set_xticklabels(labels, rotation=35, ha="right", fontsize=8)
    axis.set_ylabel(ylabel)
    axis.spines[["top", "right"]].set_visible(False)
    for pos, value in zip(positions, values):
        axis.text(pos, value, f"{value:.4g}", ha="center", va="bottom", fontsize=6.5)
    figure.tight_layout()
    _save(figure, out_dir, stem)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--measurements", type=Path,
        default=Path("outputs/efficiency/efficiency_measurements.csv"),
    )
    parser.add_argument("--out-dir", type=Path, default=Path("outputs/figures"))
    args = parser.parse_args()

    if not args.measurements.is_file():
        raise SystemExit(f"missing {args.measurements}")
    table = pd.read_csv(args.measurements)
    required = {"kind", "method", "stage", "value", "unit", "hardware", "note"}
    if missing := required.difference(table.columns):
        raise ValueError(f"{args.measurements}: missing columns {sorted(missing)}")
    if table.duplicated(["kind", "method", "stage"]).any():
        raise ValueError("duplicate efficiency measurement rows")
    values = pd.to_numeric(table["value"], errors="raise")
    if not np.isfinite(values).all() or not values.gt(0).all():
        raise ValueError("efficiency measurements must be finite and positive")
    inference_rows = table[table["kind"] == "inference"]
    if not inference_rows["note"].str.contains(
        "model execution only", case=False, na=False
    ).all():
        raise ValueError(
            "inference rows must identify the pure model-execution timing boundary"
        )
    args.out_dir.mkdir(parents=True, exist_ok=True)

    training = table[table["kind"] == "training"].set_index(["method", "stage"])
    missing_training = [key for key in TRAINING_ORDER if key not in training.index]
    if missing_training:
        raise ValueError(f"missing training-efficiency rows: {missing_training}")
    sft_seconds = float(training.loc[("UHI-E3LLM", "SFT"), "value"])
    ppo_seconds = float(training.loc[("UHI-E3LLM", "PPO"), "value"])
    distillation_seconds = float(training.loc[("UHI-E3LLM", "Distillation"), "value"])
    total_seconds = float(training.loc[("UHI-E3LLM", "Total"), "value"])
    if not np.isclose(
        total_seconds, sft_seconds + ppo_seconds + distillation_seconds,
        rtol=0, atol=1e-6,
    ):
        raise ValueError("UHI-E3LLM Total must equal SFT + PPO + Distillation time")
    labels, values, colors = [], [], []
    for method, stage in TRAINING_ORDER:
        if (method, stage) not in training.index:
            continue
        row = training.loc[(method, stage)]
        assert row["unit"] == "seconds", row["unit"]
        suffix = f" ({stage})" if method == "UHI-E3LLM" else ""
        labels.append(f"{display_name(method)}{suffix}")
        values.append(float(row["value"]) / 60.0)
        colors.append(GROUP_COLORS[GROUPS[method]])
    if labels:
        _bar(labels, values, colors, "Training time (minutes, log scale)",
             args.out_dir, "fig7c_training_time_log_min")

    inference = table[
        (table["kind"] == "inference") & (table["stage"] == "inference")
    ].set_index("method")
    missing_inference = [method for method in INFERENCE_ORDER if method not in inference.index]
    if missing_inference:
        raise ValueError(f"missing inference-efficiency rows: {missing_inference}")
    labels, values, colors = [], [], []
    for method in INFERENCE_ORDER:
        if method not in inference.index:
            continue
        row = inference.loc[method]
        assert row["unit"] == "ms_per_sample", row["unit"]
        labels.append(display_name(method))
        values.append(float(row["value"]))
        colors.append(GROUP_COLORS[GROUPS[method]])
    if labels:
        _bar(labels, values, colors, "Inference time (ms per sample, log scale)",
             args.out_dir, "fig7d_inference_time_log_ms")


if __name__ == "__main__":
    main()
